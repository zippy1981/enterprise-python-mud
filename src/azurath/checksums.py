"""Fingerprint each dungeon's files, so the game can tell when code and content disagree.

A dungeon is its YAML, its scaffold and solution files *and* its check code, and they
only work as a set. If one changes without the others (a half-finished upgrade, a
stray edit in an installed copy, a checkout of the wrong branch), checks fail in
confusing ways. So each dungeon's checksum is stored in the code, in
``dungeons/<id>/checksum.py``, and the game compares it with the files on disk
when it starts.

After changing anything in a dungeon, refresh the stored checksums::

    uv run python -m azurath.checksums

``tests/test_checksums.py`` fails until you do.
"""

from __future__ import annotations

import hashlib
import importlib
import sys
from importlib import resources
from importlib.resources.abc import Traversable
from pathlib import Path

CHECKSUM_FILE = "checksum.py"
SKIP_DIRS = {"__pycache__", ".pytest_cache", ".ruff_cache"}
SKIP_SUFFIXES = (".pyc", ".pyo", ".swp", "~")
SKIP_NAMES = {".DS_Store", "Thumbs.db", "desktop.ini"}  # files the OS or an editor leaves behind


def _files(folder: Traversable, prefix: str = "") -> list[tuple[str, Traversable]]:
    found: list[tuple[str, Traversable]] = []
    for entry in folder.iterdir():
        rel = f"{prefix}{entry.name}"
        if entry.is_dir():
            if entry.name not in SKIP_DIRS:
                found.extend(_files(entry, f"{rel}/"))
        elif (
            not entry.name.endswith(SKIP_SUFFIXES)
            and entry.name not in SKIP_NAMES
            and rel != CHECKSUM_FILE
        ):
            found.append((rel, entry))
    return found


def compute(folder: Traversable) -> str:
    """SHA-256 over every file's path and contents, in a fixed order.

    Line endings are normalised to ``\\n`` first, so a Windows checkout (where git may
    turn ``\\n`` into ``\\r\\n``) gets the same checksum as macOS and Linux.
    """
    digest = hashlib.sha256()
    for rel, entry in sorted(_files(folder)):
        data = entry.read_bytes().replace(b"\r\n", b"\n")
        digest.update(rel.encode("utf-8") + b"\0")
        digest.update(len(data).to_bytes(8, "big") + data)
    return digest.hexdigest()


def dungeon_folder(dungeon_id: str) -> Traversable:
    return resources.files("azurath") / "dungeons" / dungeon_id


def dungeon_ids() -> list[str]:
    root = resources.files("azurath") / "dungeons"
    return sorted(
        entry.name
        for entry in root.iterdir()
        if entry.is_dir() and (entry / "dungeon.yaml").is_file()
    )


def expected(dungeon_id: str) -> str | None:
    """The checksum stored in the code for this dungeon (None if there isn't one)."""
    try:
        module = importlib.import_module(f"azurath.dungeons.{dungeon_id}.checksum")
    except ModuleNotFoundError:
        return None
    return getattr(module, "CHECKSUM", None)


def actual(dungeon_id: str) -> str:
    return compute(dungeon_folder(dungeon_id))


def mismatch(dungeon_id: str) -> str | None:
    """A plain-language problem if the files on disk don't match the code, else None."""
    want, got = expected(dungeon_id), actual(dungeon_id)
    if want == got:
        return None
    if want is None:
        return f"the {dungeon_id} dungeon has no stored checksum"
    return (
        f"the {dungeon_id} dungeon's files don't match this version of Azurath "
        f"(expected checksum {want[:12]}, found {got[:12]})"
    )


def render(checksum: str) -> str:
    return (
        '"""Generated by `uv run python -m azurath.checksums`. Do not edit by hand."""\n'
        "\n"
        f'CHECKSUM = "{checksum}"\n'
    )


def update(source_root: Path) -> list[str]:
    """Rewrite ``dungeons/<id>/checksum.py`` under ``source_root``. Returns what changed."""
    changed = []
    for dungeon_id in sorted(
        p.name for p in (source_root / "dungeons").iterdir() if (p / "dungeon.yaml").is_file()
    ):
        folder = source_root / "dungeons" / dungeon_id
        target = folder / CHECKSUM_FILE
        text = render(compute(folder))
        old = target.read_text(encoding="utf-8") if target.exists() else None
        if old != text:
            target.write_text(text, encoding="utf-8", newline="\n")
            changed.append(dungeon_id)
    return changed


def main() -> int:
    source_root = Path(__file__).resolve().parent
    changed = update(source_root)
    for dungeon_id in changed:
        print(f"updated dungeons/{dungeon_id}/{CHECKSUM_FILE}")
    if not changed:
        print("all dungeon checksums are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
