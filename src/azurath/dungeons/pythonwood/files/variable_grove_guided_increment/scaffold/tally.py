# Some languages write ++ to add 1. Python doesn't have ++ or -- at all!
# Instead:  score += 1  means  score = score + 1
#           score -= 1  means  score = score - 1

score = 0

# STEP 1: Add 1 to score.
# score++
# score + 1
# score += 1

# STEP 2: Add 10 more.
# score = 10
# score += 10

# STEP 3: Lose 3 points. (Careful: the order of the two symbols matters!)
# score =- 3
# score -= 3

# STEP 4: Double it.
# score ** 2
# score *= 2

greeting = "Hi"

# STEP 5: += works on strings too! Stick "!" on the end of greeting.
# greeting + "!"
# greeting += "!"

print(score, greeting)
